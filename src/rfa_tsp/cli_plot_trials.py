from __future__ import annotations

import argparse
import json
import logging
import statistics
import sys
from collections.abc import Sequence
from pathlib import Path

import matplotlib.pyplot as plt

from . import __version__

logger = logging.getLogger(__name__)


def create_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Plot route-length / overhead distribution and convergence from an RFA trials JSON file."
    )
    parser.add_argument(
        "json_file",
        type=Path,
        help="Path to the trial-*.json file generated by 'rfa-tsp --save-trials'.",
    )
    parser.add_argument(
        "--export",
        type=Path,
        default=None,
        help="Save plot to image file (e.g. .png, .svg, .pdf) instead of showing an interactive window.",
    )
    parser.add_argument(
        "--bins",
        type=int,
        default=30,
        help="Number of histogram bins (default = 30).",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Enable verbose (DEBUG) logging output.",
    )
    parser.add_argument(
        "-V",
        "--version",
        action="version",
        version=f"%(prog)s {__version__}",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = create_argument_parser()
    args = parser.parse_args(argv)

    logging.basicConfig(
        format="%(levelname)s | %(message)s",
        level=logging.DEBUG if args.verbose else logging.INFO,
    )

    if not args.json_file.is_file():
        logger.error("File not found: %s", args.json_file)
        return 1

    data = json.loads(args.json_file.read_text(encoding="utf-8"))
    meta = data.get("meta", {})
    trials = data.get("trials", [])

    if not trials:
        logger.error("No trial records found in %s", args.json_file)
        return 1

    optimal_length = meta.get("optimal_length")
    lengths = [float(t["length"]) for t in trials]

    if optimal_length is not None:
        values = [(length / float(optimal_length) - 1.0) * 100.0 for length in lengths]
        metric_label = "Overhead vs. optimum (%)"
        unit = "%"
    else:
        values = lengths
        metric_label = "Route length"
        unit = ""

    mean_val = statistics.mean(values)
    stdev_val = statistics.stdev(values) if len(values) >= 2 else 0.0
    best_val = min(values)
    best_idx = values.index(best_val)
    best_seed = trials[best_idx]["seed"]

    # Running best curve
    running_best: list[float] = []
    current_best = float("inf")
    for val in values:
        current_best = min(current_best, val)
        running_best.append(current_best)

    logger.info("Loaded %d trials for %s", len(trials), meta.get("instance", "unknown"))
    logger.info(
        "Best: %.2f%s (seed %s) | Mean: %.2f%s ± %.2f%s", best_val, unit, best_seed, mean_val, unit, stdev_val, unit
    )

    fig, (ax_hist, ax_conv) = plt.subplots(1, 2, figsize=(12, 4.8), dpi=120)

    # Left panel: distribution histogram
    ax_hist.hist(values, bins=args.bins, color="#3b6e8c", alpha=0.75, edgecolor="white")
    ax_hist.axvline(mean_val, color="#d95f02", linestyle="-", linewidth=1.8, label=f"Mean: {mean_val:.2f}{unit}")
    ax_hist.axvspan(
        mean_val - stdev_val,
        mean_val + stdev_val,
        color="#d95f02",
        alpha=0.15,
        label=f"±1σ: {stdev_val:.2f}{unit}",
    )
    ax_hist.axvline(
        best_val, color="#1b9e77", linestyle="--", linewidth=1.8, label=f"Best: {best_val:.2f}{unit} (seed {best_seed})"
    )
    ax_hist.set_xlabel(metric_label)
    ax_hist.set_ylabel("Count")
    ax_hist.set_title("Distribution across seeds")
    ax_hist.grid(True, linestyle=":", alpha=0.5)
    ax_hist.legend(fontsize=8.5)

    # Right panel: convergence over trials
    xs = list(range(1, len(values) + 1))
    ax_conv.scatter(xs, values, s=10, color="#3b6e8c", alpha=0.25, label="Single trial")
    ax_conv.plot(xs, running_best, color="#1b9e77", linewidth=2.0, label="Best so far")
    ax_conv.set_xlabel("Trial #")
    ax_conv.set_ylabel(metric_label)
    ax_conv.set_title("Convergence of best solution")
    ax_conv.grid(True, linestyle=":", alpha=0.5)
    ax_conv.legend(fontsize=8.5)

    title = (
        f"RFA Seed Sensitivity: {meta.get('instance', '?')} "
        f"({meta.get('folding_strategy', '?')} / {meta.get('unfolding_strategy', '?')}, n={len(trials)})"
    )
    fig.suptitle(title, fontsize=11, fontweight="bold")
    fig.tight_layout()

    if args.export is not None:
        fig.savefig(args.export, dpi=150, bbox_inches="tight")
        logger.info("Plot exported to %s", args.export)
    else:
        plt.show()

    return 0


if __name__ == "__main__":
    sys.exit(main())
